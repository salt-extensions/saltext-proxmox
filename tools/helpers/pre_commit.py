import re
from pathlib import Path

from . import prompt
from .cmd import CommandNotFound
from .cmd import ProcessExecutionError
from .cmd import git
from .cmd import local
from .git import list_untracked

# Hooks sharing a prek priority run concurrently; their results are
# reported indented with box-drawing prefixes under a batch header.
PRE_COMMIT_TEST_REGEX = re.compile(
    r"^(?:\s*[┌├│└]\s)?(?P<test>[^\n]+?)\.{4,}.*(?P<resolution>Failed|Passed|Skipped)$"
)
NON_IDEMPOTENT_HOOKS = (
    # prek reports a concurrently run batch of hooks under this header when
    # files were modified - the modification cannot be attributed to a
    # specific member then, but always warrants a rerun.
    "Files were modified by following hooks",
    "trim trailing whitespace",
    "mixed line ending",
    "fix end of files",
    "Remove Python Import Header Comments",
    "Check rST doc files exist for modules/states",
    "Autoformat MyST/Markdown",
    "Salt extensions docstrings auto-fixes",
    "Rewrite the test suite",
    "Rewrite Code to be Py3.",
    "isort",
    "black",
    "blacken-docs",
)
# Wrapper that suppresses pre-commit's warnings about prek-only config keys
PRE_COMMIT_QUIET = Path(__file__).resolve().parent.parent / "pre_commit_quiet.py"
# Identifies git hook files generated by pre-commit (not prek)
PRE_COMMIT_HOOK_MARKER = "File generated by pre-commit"
# The interpreter that ran `pre-commit install`, as recorded in the hook file
INSTALL_PYTHON_REGEX = re.compile(
    r"^INSTALL_PYTHON=(?P<quote>[\"']?)(?P<path>.+?)(?P=quote)$", re.MULTILINE
)
# Identifies console scripts already patched by quiet_venv_pre_commit
QUIET_SCRIPT_MARKER = "rewritten by the dev automation"
QUIET_SCRIPT_TMPL = """\
{shebang}
# Console script for pre-commit, {marker} to suppress
# warnings about prek-only config keys (cf. tools/pre_commit_quiet.py).
import logging
import sys

logging.getLogger("pre_commit").addFilter(
    lambda record: "Unexpected key(s) present" not in record.getMessage()
)

from pre_commit.main import main

if __name__ == "__main__":
    sys.exit(main())
"""


def pre_commit_cmd():
    """
    Return the command to manage the pre-commit hooks with. Prefers prek,
    a faster drop-in replacement, when it is available, otherwise falls
    back to pre-commit. Must be called with the project venv active to
    discover executables installed into it.
    """
    try:
        return local["prek"]
    except CommandNotFound:
        return local["python"][str(PRE_COMMIT_QUIET)]


def upgrade_hook_to_prek(venv, project_root="."):
    """
    Replace a pre-commit-generated git hook with prek's when the hook
    was installed by this automation and prek is available, e.g. after
    a template migration added prek to existing dev venvs. Hooks the
    user installed themselves (via pipx etc.) are recognized by their
    recorded interpreter lying outside the project venv and left alone.
    """
    hook = Path(project_root, ".git", "hooks", "pre-commit")
    try:
        contents = hook.read_text(encoding="utf-8")
    except OSError:
        return
    if PRE_COMMIT_HOOK_MARKER not in contents:
        return
    install_python = INSTALL_PYTHON_REGEX.search(contents)
    if not install_python:
        return
    recorded = Path(install_python.group("path"))
    try:
        # Canonicalize the directory only - the venv's python executable
        # itself is usually a symlink pointing outside the venv.
        (recorded.parent.resolve() / recorded.name).relative_to(Path(venv).resolve())
    except ValueError:
        return
    with local.venv(venv):
        try:
            prek = local["prek"]
        except CommandNotFound:
            return
        prompt.status("Reinstalling the git hook with prek")
        prek("install", "-f")


def quiet_venv_pre_commit(venv):
    """
    Overwrite the pre-commit console script installed into the project
    venv with a variant that suppresses warnings about prek-only config
    keys, covering manual `pre-commit` invocations. Only rewrites
    scripts that look like pre-commit's entrypoint shim; a no-op on
    Windows (binary launchers). pre-commit reinstalls regenerate the
    script, hence this needs to be reapplied afterwards.
    """
    script = Path(venv) / "bin" / "pre-commit"
    try:
        contents = script.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return
    if QUIET_SCRIPT_MARKER in contents:
        return
    if not contents.startswith("#!") or "from pre_commit.main import main" not in contents:
        return
    shebang = contents.splitlines()[0]
    script.write_text(
        QUIET_SCRIPT_TMPL.format(shebang=shebang, marker=QUIET_SCRIPT_MARKER),
        encoding="utf-8",
    )


def quiet_installed_hook(project_root="."):
    """
    Rewrite a pre-commit-generated git hook file to invoke pre-commit
    via the pre_commit_quiet wrapper, suppressing warnings about
    prek-only config keys during commits. prek-generated hooks don't
    warn and are left alone. Idempotent; a no-op when the hook is
    absent, prek's or has an unexpected structure. pre-commit's marker
    comments are preserved, so reinstalls keep working (and need this
    treatment again).
    """
    hook = Path(project_root, ".git", "hooks", "pre-commit")
    try:
        contents = hook.read_text(encoding="utf-8")
    except OSError:
        return
    if PRE_COMMIT_HOOK_MARKER not in contents:
        return
    # Git hooks run with the work tree root as cwd
    patched = contents.replace(
        '-mpre_commit "${ARGS[@]}"',
        'tools/pre_commit_quiet.py "${ARGS[@]}"',
    )
    if patched != contents:
        prompt.status("Patching pre-commit hook to silence unknown config warnings")
        hook.write_text(patched, encoding="utf-8")


def parse_pre_commit(data):
    """
    Parse pre-commit output into a list of passing hooks and a mapping of
    failing hooks to their output.
    """
    passing = []
    failing = {}
    cur = None
    for line in data.splitlines():
        if match := PRE_COMMIT_TEST_REGEX.match(line):
            cur = None
            if match.group("resolution") != "Failed":
                passing.append(match.group("test"))
                continue
            cur = match.group("test")
            failing[cur] = []
            continue
        try:
            failing[cur].append(line)
        except KeyError:
            # in case the parsing logic fails, let's not crash everything
            continue
    return passing, {test: "\n".join(output).strip() for test, output in failing.items()}


def check_pre_commit_rerun(data):
    """
    Check if we can expect failing hooks to turn green during a rerun.
    """
    _, failing = parse_pre_commit(data)
    for hook in failing:
        if hook.startswith(NON_IDEMPOTENT_HOOKS):
            return True
    return False


def run_pre_commit(venv, retries=2):
    """
    Run pre-commit in a loop until it passes, there is no chance of
    autoformatting to make it pass or a maximum number of runs is reached.

    Usually, a maximum of two runs is necessary (if a hook reformats the
    output of another later one again). To avoid repeating the full
    (expensive) suite in that case, the file-modifying hooks are run
    until they converge first.
    """
    new_files = set()

    def _track_untracked():
        untracked_files = set(map(str, list_untracked()))
        nonlocal new_files
        new_files = new_files.union(untracked_files)
        # Ensure pre-commit runs on all paths.
        # We don't want to git add . because this removes merge conflicts
        git("add", "--intent-to-add", *untracked_files)

    def _converge_formatters():
        # Requires prek since pre-commit does not support hook groups
        # (repeated single-hook runs would negate the speedup). Without
        # it, the full-suite loop below handles reformatting as before,
        # just more slowly.
        with local.venv(venv):
            try:
                prek = local["prek"]
            except CommandNotFound:
                return
            for _ in range(retries + 1):
                _track_untracked()
                try:
                    prek("run", "--all-files", "--group", "fmt")
                except ProcessExecutionError as err:
                    if check_pre_commit_rerun(err.stdout):
                        continue
                # Converged or genuine hook failure, which the
                # following full run reports consistently.
                return

    def _run_pre_commit_loop(retries_left):
        _track_untracked()
        with local.venv(venv):
            try:
                pre_commit_cmd()("run", "--all-files")
            except ProcessExecutionError as err:
                if retries_left > 0 and check_pre_commit_rerun(err.stdout):
                    return _run_pre_commit_loop(retries_left - 1)
                raise

    prompt.status(
        "Running pre-commit hooks against all files. This can take a minute, please be patient"
    )

    try:
        _converge_formatters()
        _run_pre_commit_loop(retries)
        return True
    except ProcessExecutionError as err:
        _, failing = parse_pre_commit(err.stdout)
        if failing:
            msg = f"Please fix all ({len(failing)}) failing hooks"
        else:
            msg = f"Output: {err.stderr or err.stdout}"
        prompt.warn(f"Pre-commit is failing. {msg}")
        for i, failing_hook in enumerate(failing):
            prompt.warn(f"✗ Failing hook ({i + 1}): {failing_hook}", failing[failing_hook])
    finally:
        if new_files:
            try:
                # Check if there is at least one commit in the repo,
                # otherwise git restore --staged fails.
                git("rev-parse", "HEAD")
            except ProcessExecutionError:
                pass
            else:
                # Undo git add --intent-to-add to allow RenovateBot to detect new files correctly
                git("restore", "--staged", *new_files)
    return False
